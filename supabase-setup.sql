create table if not exists responses (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  ip_address text,
  user_agent text,
  q1 int, q2 int, q3 int, q4 int, q5 int, q6 int, q7 int, q8 int
);

alter table responses enable row level security;

-- Anyone can submit (insert) a response.
drop policy if exists "anon can insert" on responses;
create policy "anon can insert"
  on responses for insert
  to anon
  with check (true);

-- Anyone can read (needed by the admin dashboard; the admin page has its own password gate).
drop policy if exists "anon can select" on responses;
create policy "anon can select"
  on responses for select
  to anon
  using (true);

